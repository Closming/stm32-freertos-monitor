/**
  * @brief This function handles USART1 global interrupt.
  *
  * ★ 这个函数是整个串口发送链路的**最后一环**，缺了它串口只能发一次。
  *
  *   STM32F1 的 HAL 把"UART DMA 发送完成"拆成了两步：
  *     ① DMA 搬完最后一个字节 -> DMA1_Channel4_IRQHandler
  *        -> UART_DMATransmitCplt() 里 SET_BIT(CR1, USART_CR1_TCIE)
  *           （打开 USART 的"发送完成"中断，等最后一字节真正移出移位寄存器）
  *     ② USART1 的 TC 中断 -> 本函数 -> HAL_UART_IRQHandler()
  *        -> UART_EndTransmit_IT() 里做两件事：
  *             huart->gState = HAL_UART_STATE_READY   （解锁发送状态）
  *             HAL_UART_TxCpltCallback()              （放行 s_tx_done 信号量）
  *
  *   第 ② 步一旦缺失，gState 就永远停在 HAL_UART_STATE_BUSY_TX，
  *   之后**所有**发送都会直接返回 HAL_BUSY —— 包括轮询发送的日志。
  *   现象很迷惑人：串口能收到**第一帧**（那次 DMA 是真的发出去了），
  *   然后一条数据、一条日志都再也收不到，而板子本身完全正常
  *   （LED 心跳照闪、看门狗照喂），看起来像"固件卡死"但又不是。
  *
  *   ⚠️ 本函数依赖 NVIC 里 USART1_IRQn 被使能，见 Src/usart.c 的
  *      HAL_UART_MspInit。两处必须同时存在。
  */
