/**
  ******************************************************************************
  * @file    app_adc.h
  * @brief   ADC 双通道采集（扫描模式 + DMA 循环搬运）。
  *
  * ── 为什么用 DMA 而不是中断 ─────────────────────────────────────────
  *
  * 中断方式下，**每一个采样点**都要打断 CPU 一次去取结果。两通道高频
  * 采样时，CPU 有相当比例的时间耗在进出中断上，而这些数据本身毫无
  * 处理价值——它们只是原始值，后面还要滤波。
  *
  * DMA 方式下数据**自己流进内存数组**，CPU 完全不用管；任务需要时
  * 直接读数组即可。这是"高采集率"场景的标准做法。
  *
  * ── 接线注意 ────────────────────────────────────────────────────────
  *
  * 光敏接的是**现成的光敏模块**的 `AO` 输出 —— 模块板上自带分压，`AO` 就是那个分压点
  * （原理等价于"光敏电阻 + 固定电阻"的分压网络，但**不是自己搭的**）。
  * 电位器两端接 3.3V，中间抽头接 PA2。
  * ★ 绝对不能接 5V —— ADC 输入不得超过 VDDA（3.3V），接 5V 会打坏引脚。
  ******************************************************************************
  */

#ifndef __APP_ADC_H
#define __APP_ADC_H

#include <stdint.h>
#include <stdbool.h>
#include "app_config.h"

/** 一次采样的两路模拟量 */
typedef struct
{
    uint16_t light;   /**< 光敏电阻分压值，0~4095 */
    uint16_t pot;     /**< 电位器分压值，0~4095 */
} adc_sample_t;

/**
 * @brief 启动 ADC + DMA 的循环采集。
 *
 * 调用后 DMA 会**持续不断**地把两个通道的值搬进内部缓冲区，
 * 不需要（也不能）反复调用本函数。在 scheduler 启动前调用。
 */
void adc_init(void);

/**
 * @brief 读取经过 8 点滑动平均滤波的采样值。
 *
 * 每调用一次就把当前原始值推进滑动窗口一格，并返回窗口内的平均值。
 * 所以**调用频率应当接近采样周期**，否则窗口里装的是同一批数据，
 * 滤波就失去意义。
 *
 * 为什么要滤波：光敏电阻分压点直接接 ADC，电源纹波和杜邦线的接触
 * 抖动都会体现在读数上，原始值跳动几十个字很常见。滑动平均能把
 * 这类高频噪声压下去，同时几乎不引入延迟（8 点窗口，50ms 周期 = 400ms
 * 的等效延迟，对"环境监测"这个应用完全够用）。
 *
 * @param out 滤波后的采样值
 */
void adc_get_filtered(adc_sample_t *out);

/**
 * @brief 读取**未经滤波**的原始值，用于标定时对照。
 * @param out 原始采样值
 */
void adc_get_raw(adc_sample_t *out);

#endif /* __APP_ADC_H */
