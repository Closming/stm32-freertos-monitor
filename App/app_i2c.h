/**
  ******************************************************************************
  * @file    app_i2c.h
  * @brief   GPIO 软件模拟 I²C + **总线互斥锁**。本项目的核心模块。
  *
  * ── 这个文件为什么重要 ──────────────────────────────────────────────
  *
  * SHT30（0x44）和 SSD1306（0x3C）挂在同一条 I²C 总线上，分别由
  * TaskSensor 和 TaskDisplay 两个**不同优先级的任务**驱动。
  *
  * 问题：TaskSensor 正在读 SHT30（一次完整事务约 15ms），
  *      TaskDisplay 抢占并开始刷 OLED —— 两边的位操作交错在同样的
  *      两根 GPIO 上，总线时序彻底乱掉，表现为应答超时、读数偶发错乱。
  *
  * 实训时的做法是"在两次通信之间补足延时"——治标。延时能降低碰撞概率，
   * 但**不能消除**，因为两个任务的相对时序由调度器决定，不由延时决定。
  *
  * 这里的做法：**任何 I²C 事务都必须先拿到互斥锁**，把"两根线的电平状态"
   * 当成需要独占访问的临界资源。这是从调度层面根治，而不是概率上缓解。
  *
  * ── 正确用法 ────────────────────────────────────────────────────────
  *
  *   static bool sht30_read_op(void *ctx)
  *   {
  *       sht30_ctx_t *c = (sht30_ctx_t *)ctx;
  *       i2c_bus_start();
  *       if (!i2c_bus_write(SHT30_I2C_ADDR | 0)) { i2c_bus_stop(); return false; }
  *       ...
  *       i2c_bus_stop();
  *       return true;
  *   }
  *
  *   bool ok = i2c_transaction(sht30_read_op, &ctx, I2C_TIMEOUT_MS);
  *
  * ★ i2c_bus_* 这四个原语**自己不加锁**，只能在上面的回调里调用。
  *   在回调外面直接用它们 = 绕过了保护，等于白做。
  ******************************************************************************
  */

#ifndef __APP_I2C_H
#define __APP_I2C_H

#include <stdint.h>
#include <stdbool.h>
#include "app_config.h"

/**
 * @brief 一次 I²C 事务的实现体。**在持有总线锁的状态下被调用。**
 *
 * @param ctx 由调用者透传的上下文（缓冲区指针等）
 * @return true 事务成功；false 失败（调用者应视作本次读数无效）
 */
typedef bool (*i2c_op_fn)(void *ctx);

/* ==========================================================================
 * 初始化
 * ========================================================================== */

/**
 * @brief 创建 I²C 总线互斥锁并把两条线置为空闲（都为高）。
 *
 * 必须在调度器启动**之前**调用，或在调度器启动后由一个任务调用。
 * 创建失败会进入 Error_Handler()。
 */
void i2c_init(void);

/* ==========================================================================
 * 事务封装（带锁）
 * ========================================================================== */

/**
 * @brief 在互斥锁保护下执行一次完整 I²C 事务。
 *
 * 锁的属性是 `osMutexPrioInherit | osMutexRecursive`：
 *
 * - **优先级继承**：低优先级的 TaskDisplay 持锁时，若有高优先级任务
 *   来抢这把锁，系统会临时把 Display 提到同等优先级，让它赶紧跑完释放。
 *   不加这个属性会出现"优先级反转"——中优先级任务把持锁的低优先级任务
 *   饿死，导致所有等锁的任务一起卡住。
 *
 * - **递归**：同一次事务内部可能嵌套获取（例如刷 OLED 时先写命令段、
 *   再写数据段，两段都各自想加锁）。递归锁允许同一任务重复获取，
 *   否则会自己把自己锁死。
 *
 * @param fn         事务实现体
 * @param ctx        透传给 fn 的上下文
 * @param timeout_ms 拿锁超时（毫秒）。超时返回 false，**放弃本次操作**
 *                   —— 宁可不读这一次数据，也不阻塞任务
 * @return fn 的返回值；拿锁超时则返回 false
 */
bool i2c_transaction(i2c_op_fn fn, void *ctx, uint32_t timeout_ms);

/* ==========================================================================
 * 总线原语 —— ★ 只能在 i2c_transaction 的回调内部使用（它们不加锁）
 * ========================================================================== */

/** @brief 起始条件：SCL 为高时把 SDA 拉低 */
void i2c_bus_start(void);

/** @brief 停止条件：SCL 为高时把 SDA 释放为高 */
void i2c_bus_stop(void);

/**
 * @brief 发送一个字节并读应答
 * @return true = 从机应答（ACK）；false = 无应答（NACK，通常意味着器件不在）
 */
bool i2c_bus_write(uint8_t byte);

/**
 * @brief 读一个字节
 * @param ack true = 读完发 ACK（还要继续读）；false = 发 NACK（最后一个字节）
 */
uint8_t i2c_bus_read(bool ack);

/* ==========================================================================
 * 诊断
 * ========================================================================== */

/** @brief 累计"拿锁超时"次数。跑起来后这个数应该一直是 0 */
uint32_t i2c_get_timeout_count(void);

/** @brief 累计"总线仲裁失败/器件无应答"次数 */
uint32_t i2c_get_nack_count(void);

#endif /* __APP_I2C_H */
