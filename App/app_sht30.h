/**
  ******************************************************************************
  * @file    app_sht30.h
  * @brief   SHT30 温湿度传感器驱动（I²C，单次测量模式）。
  *
  * 器件要点：
  *   - 7 位地址 0x44（左移一位后是 0x88，见 app_config.h）
  *   - 温湿度各自带一个 CRC8 校验字节，多项式 0x31 / 初值 0xFF
  *   - 单次测量分两步：先下命令，等约 15ms，再读 6 个字节
  ******************************************************************************
  */

#ifndef __APP_SHT30_H
#define __APP_SHT30_H

#include <stdint.h>
#include <stdbool.h>
#include "app_config.h"

/** 一次读数的结果 */
typedef struct
{
    int16_t  temp_x100;   /**< 温度 ×100（2365 = 23.65℃） */
    int16_t  humi_x100;   /**< 湿度 ×100（6042 = 60.42 %RH） */
} sht30_data_t;

/**
 * @brief 触发一次测量并读回结果。
 *
 * **内部是两次独立的 I²C 事务**，中间让出 CPU 等待转换完成：
 *
 *   事务 1：发测量命令        （持锁 < 1ms）
 *   osDelay(20)              ← 等待转换，**此时不持锁**
 *   事务 2：读 6 字节结果      （持锁 < 1ms）
 *
 * ★ 为什么这样拆：I²C 总线需要保护的只是"一次事务的原子性"，
 *   不是"整个测量流程"。如果把 15ms 的等待也放进临界区，TaskDisplay
 *   刷 OLED 就得干等 15ms。拆开之后持锁时间从 15ms 降到 1ms 以内 ——
 *   **互斥锁保护的是总线，不是流程**，这条是设计时的关键判断。
 *
 * @param out 读数结果。**只有返回 true 时内容才有效**
 * @return true = 读数有效；false = 通信失败或 CRC 校验不过
 */
bool sht30_read(sht30_data_t *out);

/**
 * @brief 累计 CRC 校验失败的次数。
 *
 * 单独统计它的原因：I²C 通信"能通但数据错"和"完全不通"是两种不同的
 * 故障。前者通常是总线争用/干扰，后者通常是接线或地址问题。
 * 这个计数在验证互斥锁是否真的解决了总线争用时是直接证据。
 */
uint32_t sht30_get_crc_error_count(void);

#endif /* __APP_SHT30_H */
