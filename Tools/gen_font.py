"""把 ASCII 点阵字体定义生成 C 表（App/app_font.c）。

为什么要有这个脚本，而不是直接把字体表手敲进 C 文件：

  SSD1306 的字体是一张 5×7 点阵表，手敲几百个十六进制常量，敲错了
  **不会有任何报错**——只会显示成错误的字形，极难定位。

  这里把字形写成人能看懂的 '#' / '.' 点阵图，脚本负责转成字节，
  并且提供 --show 模式把字节**还原回点阵图**，肉眼就能核对。

用法：
    python Tools/gen_font.py           # 生成 App/app_font.c 和 app_font.h
    python Tools/gen_font.py --show    # 把全部字形渲染成点阵图打印出来
    python Tools/gen_font.py --show "TEMP 23.6"   # 渲染一段文字

字形约定：
  · 每个字 5 列 × 7 行，左边是第 0 列（最高位对应第 0 行）。
  · 每列存成一个字节，bit0 = 最上面那一行的像素。
  · 字库只收录**本项目实际会用到**的字符：数字、大写字母、少量符号。
    刻意不收小写字母——显示内容全部用大写，能把表缩小一半。
"""

