#: 字库覆盖 0x20 ~ 0x7F，即全部可打印 ASCII。
#:
#: 为什么范围要连续：查表下标 = 字符 - FIRST_CHAR，中间有空洞就会串位。
#: 范围里用不到的字符一律填成空格字形（只浪费一点 flash，换掉一整类错误）。
#: 96 个字符 × 5 字节 = 480 字节 —— STM32F103C8 有 64KB flash，可以接受。
FIRST_CHAR = 0x20  # 空格
LAST_CHAR = 0x7F   # DEL

#: 非 ASCII 的自定义字形，塞进 ASCII 里**没有可打印含义**的槽位。
#: 0x7F 是 DEL，正常文本绝不会出现，拿来放度符号正合适。
#: 这样查表逻辑不用为它开特例，保持"下标 = 字符 - 0x20"这一条规则。
CUSTOM_GLYPHS: dict[int, str] = {0x7F: "°"}


#: 点阵图里表示"这个像素亮"的字符。用 '1' 写起来比 '#' 对齐得清楚，
#: 但两种都认，方便从别处拷字形进来时不用改。
_SET_CHARS = "#1"


def _glyph_columns(rows: tuple[str, ...]) -> list[int]:
    """把 5×7 的点阵图转成 5 个列字节。bit0 = 最上面一行。"""
    if len(rows) != 7 or any(len(r) != 5 for r in rows):
        raise ValueError(f"字形尺寸必须是 5 列 × 7 行，得到 {len(rows)} 行")

    cols = []
    for x in range(5):
        byte = 0
        for y in range(7):
            if rows[y][x] in _SET_CHARS:
                byte |= 1 << y
        cols.append(byte)
    return cols


def build_table() -> dict[int, list[int]]:
    """生成从 FIRST_CHAR 到 LAST_CHAR 的完整码表，空位填空格。"""
    blank = _glyph_columns(FONT[" "])
    table: dict[int, list[int]] = {}

    for code in range(FIRST_CHAR, LAST_CHAR + 1):
        if code in CUSTOM_GLYPHS:
            table[code] = _glyph_columns(FONT[CUSTOM_GLYPHS[code]])
        elif chr(code) in FONT:
            table[code] = _glyph_columns(FONT[chr(code)])
        else:
            table[code] = list(blank)
    return table


#: CUSTOM_GLYPHS 的反查表，渲染核对时用
_CUSTOM_INV = {v: k for k, v in CUSTOM_GLYPHS.items()}


# ---------------------------------------------------------------- 渲染（核对用）

def render(text: str) -> str:
    """把一段文字用字库渲染成点阵图，用来肉眼核对字形。"""
    table = build_table()
    lines = ["" for _ in range(7)]

    for ch in text:
        code = _CUSTOM_INV.get(ch, ord(ch))
        cols = table.get(code, table[FIRST_CHAR])
        for y in range(7):
            row = "".join("#" if (cols[x] >> y) & 1 else "." for x in range(5))
            lines[y] += row + "."

    return "\n".join(lines)


# ---------------------------------------------------------------- 生成 C

def emit_c(table: dict[int, list[int]]) -> str:
    lines = [
        "/**",
        "  ******************************************************************************",
        "  * @file    app_font.c",
        "  * @brief   5×7 点阵字库，供 SSD1306 显示 ASCII 文本。",
        "  *",
        "  * ★ 本文件由 Tools/gen_font.py **自动生成**，不要手工编辑。",
        "  *   要改字形或加字符，改脚本里的 FONT 定义后重新运行：",
        "  *       python Tools/gen_font.py",
        "  *   脚本的 --show 模式能把生成结果渲染回点阵图，改完务必看一眼。",
        "  *",
        "  * 编码：每个字符占 5 字节，一列一字节，bit0 = 最上面一行的像素。",
        "  *      查表下标 = ASCII 码 - 0x20。",
        "  ******************************************************************************",
        "  */",
        "",
        '#include "app_font.h"',
        "",
        "const uint8_t g_font5x7[] =",
        "{",
    ]

    for code in sorted(table):
        cols = table[code]
        # 标出字符，方便在源文件里定位某一行是哪几个字形
        if code in CUSTOM_GLYPHS:
            label = f"  /* '{CUSTOM_GLYPHS[code]}' (自定义) */"
        elif code == FIRST_CHAR:
            label = "  /* ' ' */"
        elif chr(code) in FONT:
            label = f"  /* '{chr(code)}' */"
        else:
            label = ""
        body = ", ".join(f"0x{b:02X}" for b in cols)
        lines.append(f"    {body},{label}")

    lines += [
        "};",
        "",
        f"/* 覆盖 0x{FIRST_CHAR:02X} ~ 0x{LAST_CHAR:02X}，共 "
        f"{LAST_CHAR - FIRST_CHAR + 1} 个字符，每个 5 字节，"
        f"合计 {(LAST_CHAR - FIRST_CHAR + 1) * 5} 字节 */",
        "",
    ]
    return "\n".join(lines)


def emit_h() -> str:
    return "\n".join([
        "/**",
        "  ******************************************************************************",
        "  * @file    app_font.h",
        "  * @brief   5×7 点阵字库接口。",
        "  *",
        "  * ★ 由 Tools/gen_font.py 自动生成，不要手工编辑。",
        "  ******************************************************************************",
        "  */",
        "",
        "#ifndef __APP_FONT_H",
        "#define __APP_FONT_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define FONT_FIRST_CHAR   0x{FIRST_CHAR:02X}u",
        f"#define FONT_LAST_CHAR    0x{LAST_CHAR:02X}u",
        "#define FONT_CHAR_WIDTH   5u   /**< 字形宽（像素） */",
        "#define FONT_CHAR_HEIGHT  7u   /**< 字形高（像素） */",
        "#define FONT_CHAR_SPACING 6u   /**< 含右侧留白的推进宽度 */",
        "",
        "/** 字库表。下标 = ASCII 码 - FONT_FIRST_CHAR，每字符 5 字节。 */",
        "extern const uint8_t g_font5x7[];",
        "",
        "/** 度符号的字符串写法。",
        " *",
        " * ★ 必须像这样**分段**拼接：",
        " *       ssd1306_printf(0, \"TEMP 23.6\" FONT_DEG \"C\");",
        " *",
        " *   写成 \"TEMP 23.6\\x7FC\" 是错的：C 的十六进制转义是**贪婪匹配**，",
        " *   编译器会把 \\x7FC 整个当成一个转义序列（值 0x7FC），",
        " *   结果是报错或者字符被截断。分段写法里转义在引号处自然结束。",
        " */",
        '#define FONT_DEG "\\x7F"',
        "",
        "#endif /* __APP_FONT_H */",
        "",
    ])


def main() -> int:
    args = sys.argv[1:]

    if args and args[0] == "--show":
        text = args[1] if len(args) > 1 else "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .:-/%+!=?*_"
        for i in range(0, len(text), 30):
            chunk = text[i:i + 30]
            print(f"--- {chunk!r} ---")
            print(render(chunk))
            print()
        return 0

    root = Path(__file__).resolve().parent.parent
    out_dir = root / "App"

    (out_dir / "app_font.c").write_text(emit_c(build_table()), encoding="utf-8")
    (out_dir / "app_font.h").write_text(emit_h(), encoding="utf-8")

    print(f"已生成 {out_dir / 'app_font.c'}")
    print(f"已生成 {out_dir / 'app_font.h'}")
    print(f"字符数 {LAST_CHAR - FIRST_CHAR + 1}，占用 "
          f"{(LAST_CHAR - FIRST_CHAR + 1) * 5} 字节 flash")
    return 0


if __name__ == "__main__":
    sys.exit(main())
